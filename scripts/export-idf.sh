#!/usr/bin/env bash
# Cache the ESP-IDF environment exports to prevent repeated 8+ second activation runs
# on every mise hook-env / shell prompt evaluation.

CACHE_FILE="${IDF_ENV_CACHE:-$HOME/.espressif/idf_export_cache.sh}"
IDF_DIR="${IDF_PATH:-$HOME/esp/esp-idf}"

if [ "${1:-}" = "--refresh" ] || [ -n "${REFRESH_IDF_ENV:-}" ]; then
    rm -f "$CACHE_FILE"
fi

if [ -f "$CACHE_FILE" ] && [ -s "$CACHE_FILE" ]; then
    # shellcheck disable=SC1090
    . "$CACHE_FILE"
    return 0 2>/dev/null || exit 0
fi

if [ -f "$IDF_DIR/export.sh" ]; then
    # shellcheck disable=SC1090
    . "$IDF_DIR/export.sh" >/dev/null 2>&1

    # Extract the static export statements generated by ESP-IDF activate_venv
    LATEST_ACTIVATE=$(ls -t /tmp/esp_idf_activate_*/* 2>/dev/null | head -1)
    if [ -n "$LATEST_ACTIVATE" ] && [ -f "$LATEST_ACTIVATE" ]; then
        mkdir -p "$(dirname "$CACHE_FILE")"
        grep -E '^export (IDF_PATH|ESP_IDF_VERSION|IDF_PYTHON_ENV_PATH|OPENOCD_SCRIPTS|ESP_ROM_ELF_DIR|IDF_TOOLS_INSTALL_CMD|IDF_TOOLS_EXPORT_CMD|PATH)=' "$LATEST_ACTIVATE" > "$CACHE_FILE"
    fi
fi
